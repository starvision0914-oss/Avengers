export default function SmartStorePromptModal(
  { open, onClose }: { open: boolean; onClose: () => void },
) {
  if (!open) return null;
  const copy = async () => {
    try {
      if (navigator.clipboard && window.isSecureContext) {
        await navigator.clipboard.writeText(PROMPT);
      } else {
        const ta = document.createElement('textarea');
        ta.value = PROMPT;
        ta.style.position = 'fixed';
        ta.style.left = '-9999px';
        document.body.appendChild(ta);
        ta.focus();
        ta.select();
        const ok = document.execCommand('copy');
        document.body.removeChild(ta);
        if (!ok) throw new Error('execCommand copy failed');
      }
      toast.success('프롬프트가 복사되었습니다');
    } catch {
      toast.error('복사 실패 — 입력창 클릭 후 Ctrl+A → Ctrl+C 하세요');
    }
  };
  return (
    <div className="fixed inset-0 z-50 bg-black/50 flex items-center justify-center p-4" onClick={onClose}>
      <div className="w-full max-w-3xl max-h-[88vh] rounded-xl border bg-white border-gray-200 text-gray-900 flex flex-col" onClick={e => e.stopPropagation()}>
        <div className="flex items-center gap-2 px-5 py-3 border-b border-gray-200">
          <h3 className="text-[14px] font-bold">스마트스토어 상품명·키워드·속성 최적화 — AI 프롬프트</h3>
          <button onClick={copy} className="ml-auto px-3 py-1.5 text-[12px] font-semibold bg-emerald-600 hover:bg-emerald-700 text-white rounded">📋 복사</button>
          <button onClick={onClose} className="text-gray-400 hover:text-gray-700 text-[15px] px-1">✕</button>
        </div>
        <div className="p-4 overflow-hidden flex flex-col">
          <p className="text-[12px] mb-2 text-gray-500">
            아래 프롬프트를 <b>📋 복사</b>해서 ChatGPT·Claude 등 AI에 붙여넣고, 원본 상품명·카테고리·제품정보를 주면
            네이버쇼핑 최적화 상품명 + 검색태그 + 상품속성을 JSON으로 생성합니다.
            <span className="text-gray-400"> (전계정 클린위반 실측 반영)</span>
          </p>
          <textarea
            readOnly
            value={PROMPT}
            onFocus={e => e.currentTarget.select()}
            className="w-full h-[60vh] text-[12px] leading-[1.5] font-mono p-3 rounded border resize-none bg-gray-50 border-gray-200 text-gray-800"
          />
        </div>
      </div>
    </div>
  );
}
